public class rightShift {
    public static void main(String[] args) {

        int a = 20;

        System.out.println("Original Number : " + a);
        System.out.println("a >> 1 = " + (a >> 1));
        System.out.println("a >> 2 = " + (a >> 2));
        System.out.println("a >> 3 = " + (a >> 3));
    }
}
